-- ============================================================
--  마라톤 코치룸 — 과제 독려 문구에서 「이번 주」 빼기 (migration-055-nudge-text.sql · 20261101h)
--
--  실행 방법
--    054 다음에 Supabase 대시보드 → SQL Editor → New query → 이 파일 전체를 붙여넣고 Run.
--  여러 번 실행해도 안전하다. 학생 · 기록은 바꾸지 않는다. 함수 배포는 필요 없다.
--
--  과제 독려 대상이 「지난 수업 이후」(직전 주 + 진행 중)로 바뀌어 {밀린날짜}에 직전 주 날짜도 들어간다.
--  「과제 독려(학생)」 · 「과제 독려(학부모)」 글이 054 기본 글 그대로일 때만 「지난 수업 이후」로 바꾼다
--  (코치룸에서 고쳐 저장한 글은 건드리지 않는다)
-- ============================================================

update public.sms_templates
   set body = '[마라톤국어] {학생이름} 학생, 지난 수업 이후 과제 {밀린날짜}이 아직 제출 안 됐어요. 오늘 안에 마라톤 앱에서 제출해 주세요!',
       updated_by = 'migration-055'
 where btrim(title) = '과제 독려(학생)'
   and body = '[마라톤국어] {학생이름} 학생, 이번 주 과제 {밀린날짜}이 아직 제출 안 됐어요. 오늘 안에 마라톤 앱에서 제출해 주세요!';

update public.sms_templates
   set body = '[마라톤국어] {학생이름} 학생의 지난 수업 이후 과제 중 {밀린날짜}이 아직 제출되지 않았습니다. 확인 부탁드립니다.',
       updated_by = 'migration-055'
 where btrim(title) = '과제 독려(학부모)'
   and body = '[마라톤국어] {학생이름} 학생의 이번 주 과제 중 {밀린날짜}이 아직 제출되지 않았습니다. 확인 부탁드립니다.';


-- ============================================================
--  확인 — 한 줄 true (「이번 주」가 남은 과제 독려 기본 글이 없음)
-- ============================================================
select '과제 독려 문구' as what,
       (not exists (select 1 from public.sms_templates
                     where btrim(title) in ('과제 독려(학생)', '과제 독려(학부모)')
                       and updated_by = 'migration-054' and body like '%이번 주 과제%'))::text as ok;
